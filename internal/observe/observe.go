// Package observe defines the chat-completion observation contract that the
// proxy publishes and its consumers (stats, watchdog, ...) subscribe to.
//
// The proxy always taps every /v1/chat/completions response (streaming and
// non-streaming) and parses the completion's token/decode statistics out of
// it. Each parsed Observation is fanned out to every registered Consumer.
// Parsing and interception live in the proxy; a consumer only reacts to the
// already-parsed Observation.
package observe

import "sync"

// Observation is the token and decode statistics one chat completion reports,
// parsed by the proxy from the response (the final usage chunk for a stream,
// the JSON body for a non-stream response).
type Observation struct {
	Prompt        int // prompt tokens (input)
	Cached        int // prompt tokens served from the backend prefix cache (input cache)
	Completion    int // generated tokens (output)
	Total         int // prompt + completion
	DraftN        int // MTP/speculative draft tokens attempted (0 when not reported)
	DraftAccepted int // MTP/speculative draft tokens accepted (0 when not reported)
	// Cloud reports that the completion was served by the cloud fallback backend
	// instead of the local one. Stats accounts it in the day's cloud counters; a
	// consumer that only judges the local model (the watchdog) never receives a
	// cloud observation at all, unless it opts in via CloudConsumer
	Cloud bool
}

// ErrorInfo is one backend error event observed on a chat completion response: an
// OpenAI-style top-level "error" object carried either by a stream data event
// (`data: {"error":{...}}`) or by a non-stream JSON body (`{"error":{...}}`). The
// proxy extracts it from the tapped response and hands it to the error guard.
type ErrorInfo struct {
	Type    string // error.type (e.g. "server_error")
	Message string // error.message (matched against the configured patterns)
	Code    string // error.code (optional)
}

// HasDraft reports whether the observation carries MTP/speculative draft data.
func (o Observation) HasDraft() bool { return o.DraftN > 0 }

// DraftRate is the MTP draft acceptance ratio in [0,1]; only meaningful when
// HasDraft is true.
func (o Observation) DraftRate() float64 {
	if o.DraftN <= 0 {
		return 0
	}
	return float64(o.DraftAccepted) / float64(o.DraftN)
}

// Consumer reacts to one observed chat completion. Implementations must be
// safe for concurrent use: Observations are delivered from the proxy's per-
// request response path, so many completions may be observed at once.
type Consumer interface {
	OnCompletion(o Observation)
}

// CloudConsumer opts a consumer in to the observations of cloud-routed
// completions. A consumer that does not implement it, or whose ConsumeCloud
// returns false, only ever sees local completions: the hub never delivers a
// cloud observation to it. The watchdog judges the local model (draft
// acceptance, degenerate output), so it deliberately stays out of cloud traffic;
// stats implements it to account the cloud usage separately.
type CloudConsumer interface {
	ConsumeCloud() bool
}

// consumesCloud reports whether c opted in to cloud observations
func consumesCloud(c Consumer) bool {
	cc, ok := c.(CloudConsumer)
	return ok && cc.ConsumeCloud()
}

// StreamConsumer observes the lifecycle and generated content of in-flight
// /v1/chat/completions responses (streaming and non-streaming). Implementations
// must be safe for concurrent use: completions overlap, and content is
// delivered from the proxy's per-request stream-copy path.
type StreamConsumer interface {
	// OnStreamStart is called when one chat completion response begins
	OnStreamStart(id int, stream bool)
	// OnStreamContent is called with a piece of content generated by one streaming
	// completion (content and reasoning_content); it is never called for a
	// non-streaming completion (its content only exists at EOF)
	OnStreamContent(id int, content string)
	// OnStreamEnd is called when the completion response body is closed
	OnStreamEnd(id int)
}

// Hub fans an Observation out to every registered consumer. It is safe for
// concurrent use.
type Hub struct {
	mu             sync.RWMutex
	consumers      []Consumer
	streams        []StreamConsumer
	cloudConsumers int
	nextStreamID   int
}

// Register adds a consumer; a nil consumer is ignored.
func (h *Hub) Register(c Consumer) {
	if c == nil {
		return
	}
	h.mu.Lock()
	h.consumers = append(h.consumers, c)
	if consumesCloud(c) {
		h.cloudConsumers++
	}
	h.mu.Unlock()
}

// Len returns the number of registered consumers.
func (h *Hub) Len() int {
	h.mu.RLock()
	n := len(h.consumers)
	h.mu.RUnlock()
	return n
}

// CloudLen returns the number of registered consumers that opted in to cloud
// observations (see CloudConsumer); 0 means no consumer needs cloud traffic
// observed, so the proxy can leave cloud responses completely untouched.
func (h *Hub) CloudLen() int {
	h.mu.RLock()
	n := h.cloudConsumers
	h.mu.RUnlock()
	return n
}

// Notify delivers the observation to all registered consumers, in registration
// order. A cloud observation is only delivered to the consumers that opted in to
// cloud traffic (CloudConsumer). With no matching consumers it is a no-op.
func (h *Hub) Notify(o Observation) {
	h.mu.RLock()
	consumers := h.consumers
	h.mu.RUnlock()
	for _, c := range consumers {
		if o.Cloud && !consumesCloud(c) {
			continue
		}
		c.OnCompletion(o)
	}
}

// RegisterStream adds a stream consumer; a nil consumer is ignored
func (h *Hub) RegisterStream(c StreamConsumer) {
	if c == nil {
		return
	}
	h.mu.Lock()
	h.streams = append(h.streams, c)
	h.mu.Unlock()
}

// StreamStart registers one in-flight chat completion response and returns its id;
// every stream consumer is notified (stream says whether the response is a stream).
// A cloud completion is never tracked (id 0, no consumer notified): stream
// consumers judge the local model's generation, so cloud traffic stays invisible
// to them, and its StreamContent/StreamEnd calls are no-ops.
func (h *Hub) StreamStart(stream, cloud bool) int {
	if cloud {
		return 0
	}
	h.mu.Lock()
	h.nextStreamID++
	id := h.nextStreamID
	consumers := h.streams
	h.mu.Unlock()
	for _, c := range consumers {
		c.OnStreamStart(id, stream)
	}
	return id
}

// StreamContent delivers one piece of generated content of one stream to every
// stream consumer; an empty piece and an untracked (cloud, id 0) stream are no-ops
func (h *Hub) StreamContent(id int, content string) {
	if id == 0 || content == "" {
		return
	}
	h.mu.RLock()
	consumers := h.streams
	h.mu.RUnlock()
	for _, c := range consumers {
		c.OnStreamContent(id, content)
	}
}

// StreamEnd unregisters one in-flight chat completion response from every stream
// consumer; an untracked (cloud, id 0) stream is a no-op
func (h *Hub) StreamEnd(id int) {
	if id == 0 {
		return
	}
	h.mu.RLock()
	consumers := h.streams
	h.mu.RUnlock()
	for _, c := range consumers {
		c.OnStreamEnd(id)
	}
}
